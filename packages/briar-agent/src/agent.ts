const AGENT_COLORS = ['green', 'yellow', 'red', 'cyan', 'white'] as const
export type AgentColor = (typeof AGENT_COLORS)[number]

export function getAgentName(id: number): string {
	return AGENT_NAMES[(id - 1) % AGENT_NAMES.length]
}

export function getAgentColor(id: number): AgentColor {
	return AGENT_COLORS[(id - 1) % AGENT_COLORS.length]
}

export function getAgentDisplayName(agent: SubAgent, allAgents: SubAgent[]): string {
	const sameName = allAgents.filter((a) => a.name === agent.name)
	return sameName.length > 1 ? `${agent.name}#${agent.id}` : agent.name
}
